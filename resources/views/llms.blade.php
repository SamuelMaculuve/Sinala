# Sinala

> Plataforma SaaS moçambicana para gestão de eventos, participantes, presenças, assinaturas digitais e pagamentos ou subsídios.

Canonical: {{ url('/') }}
Idioma principal: Português de Moçambique (pt-MZ)
Público: ONGs, associações, instituições, projectos sociais, consultorias e organizações que realizam formações, workshops e seminários.

## Funcionalidades principais

- Criar e acompanhar eventos e formações.
- Registar participantes e presenças por evento e por dia.
- Recolher assinaturas digitais no tablet com dedo ou caneta.
- Confirmar pagamentos e subsídios com assinatura do participante.
- Gerar relatórios e listas de presença ou pagamento.
- Separar dados por organização e controlar permissões de utilizadores.

## Planos

- Free: 0 MZN; até 10 eventos, 3 utilizadores, presenças e pagamentos.
- Profissional: 3.500 MZN por mês; até 20 novos eventos por mês e 5 utilizadores.
- Organização: 7.500 MZN por mês; até 100 novos eventos por mês e 20 utilizadores.

